s  = "hello world"

print(s.upper()) # Convert to uppercase
print(s.lower()) # Convert to lowercase
print(s.title()) # Convert to title case
print(s.capitalize()) # Convert to capitalize case
print(s.swapcase()) # Swap case
print(s.replace("hello", "hi")) # Replace substring
print(s.split()) # Split string
print(s.strip()) # Remove whitespace
print(s.lstrip()) # Remove leading whitespace
print(s.rstrip()) # Remove trailing whitespace
print(s.find("hello")) # Find index
print(s.index("hello")) # Find index
print(s.count("hello")) # Count occurrences
print(s.startswith("hello")) # Check if starts with
print(s.endswith("hello")) # Check if ends with
print(s.isalpha()) # Check if all alphabetic
print(s.isalnum()) # Check if all alphanumeric
print(s.isdigit()) # Check if all digits
print(s.islower()) # Check if all lowercase
print(s.isupper()) # Check if all uppercase
print(s.istitle()) # Check if all title case
print(s.isspace()) # Check if all whitespace